"""Generate SKILLS_INDEX.md and skills-index.json from skill metadata."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS_DIR = ROOT / "skills"
JSON_OUTPUT = ROOT / "skills-index.json"
MARKDOWN_OUTPUT = ROOT / "SKILLS_INDEX.md"


def load_skills() -> list[dict]:
    records = []
    for metadata_path in sorted(SKILLS_DIR.rglob("metadata.json")):
        record = json.loads(metadata_path.read_text(encoding="utf-8"))
        record["path"] = metadata_path.parent.relative_to(ROOT).as_posix()
        records.append(record)
    return sorted(records, key=lambda item: item["name"])


def render_markdown(records: list[dict]) -> str:
    lines = [
        "# Skills index",
        "",
        "> Generated by `python scripts/build-index.py`. Do not edit manually.",
        "",
        "| Skill | Category | Description | Source | Supported environments |",
        "| --- | --- | --- | --- | --- |",
    ]
    for record in records:
        source_name = record["source_repository"].rstrip("/").rsplit("/", 1)[-1]
        source = f"[{source_name}]({record['source_repository']})"
        environments = ", ".join(record["supported_agents"]) or "Not verified"
        path = record["path"]
        lines.append(
            f"| [{record['name']}]({path}/) | {record['category']} | "
            f"{record['description']} | {source} | {environments} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    records = load_skills()
    JSON_OUTPUT.write_text(
        json.dumps(records, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    MARKDOWN_OUTPUT.write_text(render_markdown(records), encoding="utf-8")
    print(f"Indexed {len(records)} skills.")


if __name__ == "__main__":
    main()
